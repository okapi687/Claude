import numpy as np


class SoldierCrabSwarm_ex_v2:
    """
    MAM_basic_ex_v2.py（MAM_basic_ex_fix.py の最新版を名前を変えて保存したもの）

    MAM_basic_ex.py（相互予期 → 追従 → 自由移動 のフェーズ順）をベースにした修正版。

    【修正点】追従（following）で移動できるのは
              「相互予期で動いた個体が空けたサイト」だけにした。

    論文1 p.7 の記述:
        "if others in the neighborhood move due to mutual anticipation,
         then the individual will move to occupy the absent site generated by
         mutual anticipation. Namely, the individual follows its predecessor."

    元の ex では、追従した個体が空けたサイトにも w=1 が立つので
    「追従 → その跡にまた追従 → …」の連鎖が起きていた。
    これが P=2 でも群れが崩れずに固まってしまう原因。

    Parameters
    ----------
    N : int
        エージェント（カニ）の数
    S : int
        格子空間の一辺の大きさ（S×Sのトーラス空間）
    L : float, default 4
        基本ベクトルの長さ
    P : int, default 15
        可能的遷移の数
    alpha : float, default 0.5
        変異角 α
    R_Nf : int, default 2
        追従者近傍の半径 R(Nf)
    R_M : int, default 3
        速度一致近傍の半径 R(M)
    c : int, default 2
        人気度の閾値 ζ ≧ c で相互予期による移動が発生する。
    follow_chain : bool, default False
        True にすると元の ex と同じ挙動（追従の連鎖あり）に戻る。比較用。
    free_wait : bool, default False
        True にすると、自由移動で行き先がふさがっている個体も
        前の個体が動いて空くまで待ってから動く（誰も動けなくなるまで繰り返す）。
        P=1 で群れが平行移動するようになる。論文に明記はないので任意オプション。
    ma_rule : {"sequential", "literal"}, default "sequential"
        相互予期で、複数の個体が同じサイトを狙ったときの扱い。
        "sequential" : ランダム順に1体ずつ、その時点で空いている最大人気度サイトへ動く
                       （途中で空いたサイトも候補になる）。これまでのモデル。
        "literal"    : 論文 p.7 を文字どおりに実装した版。
                       "If several individuals intend to move to the same site, one individual is
                        randomly chosen to move there, and the others move to the site with the
                        second highest popularity."
                       全員がステップ開始時の人気度で1番人気のサイトを「狙い」、同じサイトを狙った
                       中からランダムに1体が移動する。残りは2番目に人気のサイトへ移り、
                       そこでも取り合いに負けたら相互予期では動かない（追従・自由移動へ回る）。
                       候補はステップ開始時に空いていたサイトだけ。
    int_mode : {"floor", "ceil", "round", "trunc", "stochastic"}, default "floor"
        可能的遷移ベクトル L·η·(cos, sin) を格子の整数に直す方法（論文の Int）。
        "floor"      : 切り捨て（X ≤ x < X+1）。論文の定義どおり。
                       ただし x<0 側にずれるので、ベクトルが平均して (−0.5, −0.5) だけ左下に偏る。
        "ceil"       : 切り上げ。floor の鏡写し（右上に偏る）。偏りの向きが入れ替わるかの対照用。
        "round"      : 四捨五入（最も近い整数）。向きの偏りなし。
        "trunc"      : 0 方向への切り捨て。向きの偏りはないが、ベクトルが短くなる。
        "stochastic" : 小数部分の確率で切り上げる確率的丸め。期待値が元の実数と一致する。
    seed : int or None
        乱数シード（再現性のため）
    """

    INT_MODES = ("floor", "ceil", "round", "trunc", "stochastic")

    def __init__(self, N=100, S=50, L=4.0, P=15, alpha=0.5,
                 R_Nf=2, R_M=3, c=2, follow_chain=False, free_wait=False,
                 ma_rule="sequential", int_mode="floor", seed=None):

        # ---- 乱数生成 ----
        self.rng = np.random.default_rng(seed)

        # ---- 格子空間の設定 ----
        self.S = S

        # ---- パラメータの設定 ----
        self.N = N
        self.L = L
        self.P = P
        self.alpha = alpha
        self.R_Nf = R_Nf
        self.R_M = R_M
        self.c = c
        self.follow_chain = follow_chain
        self.free_wait = free_wait
        if ma_rule not in ("sequential", "literal"):
            raise ValueError(f'ma_rule は "sequential" か "literal"（指定値: {ma_rule!r}）')
        self.ma_rule = ma_rule
        if int_mode not in self.INT_MODES:
            raise ValueError(f"int_mode は {self.INT_MODES} のどれか（指定値: {int_mode!r}）")
        self.int_mode = int_mode
        self.seed = seed

        # 現在のステップ数
        self.t = 0

        # ---- エージェントの配置 ----
        if N > S * S:
            raise ValueError(
                f"N({N}) が格子点の総数 S*S({S*S}) を超えています。"
                " 1つの格子点に最大1体しか配置できません。"
            )

        all_sites = self.rng.permutation(S * S)[:N]
        xs = all_sites % S
        ys = all_sites // S

        # P(k, t) = (x, y)  現在地の記録
        self.position = np.stack([xs, ys], axis=1).astype(int)

        # 各エージェントの基本ベクトルの向きをランダムに初期化
        self.theta = self.rng.uniform(0.0, 2 * np.pi, size=N)

        # 非同期更新のためのフラグ w(x, y; t)（誰かが動いて空いたサイト）
        self.w = np.zeros((S, S), dtype=int)
        # 【追加】相互予期で動いた個体が空けたサイトだけを記録するフラグ
        self.w_ma = np.zeros((S, S), dtype=int)

        # occupancy[x, y] = k のインデックス, 空きなら -1
        self.occupancy = -np.ones((S, S), dtype=int)
        for k in range(N):
            x, y = self.position[k]
            self.occupancy[x, y] = k

        # 【追加】直前ステップの実際の変位（偏極度の計算に使う）
        self.last_displacement = np.zeros((N, 2), dtype=int)

        # 【追加】各ルールで動いた回数（診断用）
        self.move_counts = {"MA": 0, "follow": 0, "free": 0, "stay": 0}

        # 追従近傍のオフセットは毎回同じなので先に作っておく
        self._dx_Nf, self._dy_Nf = self._square_neighbor_offsets(R_Nf)

    # ------------------------------------------------------------------
    # 各ステップでの動作
    # ------------------------------------------------------------------

    def _square_neighbor_offsets(self, R):
        """半径Rの正方形近傍のオフセット (dx, dy) 一覧を返す（(2R+1)^2個、中心含む）"""
        rng = np.arange(-R, R + 1)
        dx, dy = np.meshgrid(rng, rng, indexing="ij")
        return dx.ravel(), dy.ravel()

    def _to_int(self, x):
        """実数の遷移成分を int_mode に従って整数にする"""
        if self.int_mode == "floor":
            return np.floor(x).astype(int)
        if self.int_mode == "ceil":
            return np.ceil(x).astype(int)
        if self.int_mode == "round":
            return np.round(x).astype(int)      # 0.5 は切り上げ（np.rint の偶数丸めを避ける）
        if self.int_mode == "trunc":
            return np.trunc(x).astype(int)
        # stochastic：小数部分 f の確率で切り上げ、1−f の確率で切り捨て
        lo = np.floor(x)
        return (lo + (self.rng.random(np.shape(x)) < (x - lo))).astype(int)

    def _generate_potential_transitions(self):
        """可能的遷移の生成（MAM_basic_ex と同じ）"""
        N, P, S, L, alpha = self.N, self.P, self.S, self.L, self.alpha

        eta = self.rng.uniform(0.0, 1.0, size=(N, P))
        xi = self.rng.uniform(-alpha * np.pi, alpha * np.pi, size=(N, P))

        # i=0 は基本ベクトル（principal vector）: eta_0=1.0, xi_0=0.0
        eta[:, 0] = 1.0
        xi[:, 0] = 0.0

        theta = self.theta[:, None]

        vx = self._to_int(L * eta * np.cos(theta + xi))
        vy = self._to_int(L * eta * np.sin(theta + xi))

        tx = np.mod(self.position[:, 0:1] + vx, S)
        ty = np.mod(self.position[:, 1:2] + vy, S)

        return np.stack([tx, ty], axis=-1)

    def _compute_target_counts(self, targets):
        """人気度の計算（MAM_basic_ex と同じ：同一個体の重複は1回と数える）"""
        N, P, _ = targets.shape
        S = self.S

        agent_idx = np.repeat(np.arange(N), P)
        flat_x = targets[:, :, 0].ravel()
        flat_y = targets[:, :, 1].ravel()
        triples = np.stack([agent_idx, flat_x, flat_y], axis=1)

        unique_triples = np.unique(triples, axis=0)

        counts = np.zeros((S, S), dtype=int)
        np.add.at(counts, (unique_triples[:, 1], unique_triples[:, 2]), 1)
        return counts

    def _best_MA_target(self, k, targets, target_counts, occupancy):
        """
        個体kが相互予期で動けるなら、その移動先を返す（動けなければ None）
        空いている遷移先の中で人気度が最大、かつ c 以上のサイト
        """
        k_targets = targets[k]
        tx, ty = k_targets[:, 0], k_targets[:, 1]
        vacant_mask = occupancy[tx, ty] == -1
        if not vacant_mask.any():
            return None
        cand_counts = np.where(vacant_mask, target_counts[tx, ty], -1)
        m = cand_counts.max()
        if m < self.c:
            return None
        tie_idx = np.flatnonzero(cand_counts == m)
        chosen_i = self.rng.choice(tie_idx)  # 同率ならランダム
        return k_targets[chosen_i]

    def _literal_MA_phase(self, targets, target_counts, occupancy, new_position, moved):
        """
        論文 p.7 を文字どおりにした相互予期（ma_rule="literal"）
          1. 各個体は、自分の遷移先のうち「ステップ開始時に空いていて人気度 ≧ c」のサイトを
             人気度の高い順に並べる（同率はランダム）
          2. 全員が1番人気のサイトを狙う → 同じサイトを狙った中からランダムに1体が移動
          3. 負けた個体は2番目に人気のサイトを狙う → 同じく取り合い
          4. それでも動けなかった個体は相互予期では動かない
        """
        vacant_at_start = occupancy == -1      # 相互予期の前なので、まだ誰も動いていない
        ranked = []
        for k in range(self.N):
            u = np.unique(targets[k], axis=0)
            z = target_counts[u[:, 0], u[:, 1]]
            ok = vacant_at_start[u[:, 0], u[:, 1]] & (z >= self.c)
            u, z = u[ok], z[ok]
            order = np.lexsort((self.rng.random(len(z)), -z))   # 人気度の降順、同率はランダム
            ranked.append([tuple(s) for s in u[order]])

        taken = set()
        bidders = list(range(self.N))
        for rank in (0, 1):                    # 1番目 → 2番目に人気のサイト
            bids = {}
            for k in bidders:
                if len(ranked[k]) > rank and ranked[k][rank] not in taken:
                    bids.setdefault(ranked[k][rank], []).append(k)
            bidders = []
            for site, ks in bids.items():
                winner = ks[self.rng.integers(len(ks))]
                self._apply_move(winner, site[0], site[1], occupancy, new_position, by_MA=True)
                moved[winner] = True
                taken.add(site)
                self.move_counts["MA"] += 1
                bidders += [k for k in ks if k != winner]

    def _follow_sites(self, k, occupancy):
        """個体kの追従近傍で、追従先として使える空きサイトの (x配列, y配列) を返す"""
        S = self.S
        x0, y0 = self.position[k]
        nbx = np.mod(x0 + self._dx_Nf, S)
        nby = np.mod(y0 + self._dy_Nf, S)

        # 【修正の本体】
        # follow_chain=False : 相互予期で空いたサイト (w_ma) だけ
        # follow_chain=True  : 誰かが動いて空いたサイト (w)（元の ex と同じ）
        flag = self.w if self.follow_chain else self.w_ma
        is_freed = (flag[nbx, nby] == 1) & (occupancy[nbx, nby] == -1)
        return nbx[is_freed], nby[is_freed]

    def _apply_move(self, k, nx, ny, occupancy, new_position, by_MA=False):
        """個体kを (nx, ny) に動かして各種フラグを更新する"""
        x0, y0 = self.position[k]
        occupancy[x0, y0] = -1
        occupancy[nx, ny] = k
        self.w[x0, y0] = 1
        if by_MA:
            self.w_ma[x0, y0] = 1
        new_position[k] = (nx, ny)

    def step(self):
        """1タイムステップ分の更新を行う"""
        N, S = self.N, self.S

        # ---- 非同期更新の準備 ----
        self.w[:, :] = 0
        self.w_ma[:, :] = 0

        # ---- 可能的遷移の生成 と 人気度の事前計算 ----
        targets = self._generate_potential_transitions()
        target_counts = self._compute_target_counts(targets)

        occupancy = self.occupancy.copy()
        new_position = self.position.copy()
        moved = np.zeros(N, dtype=bool)

        # === 相互予期 ===
        if self.ma_rule == "literal":
            self._literal_MA_phase(targets, target_counts, occupancy, new_position, moved)

        # sequential：未移動の個体をランダム順に見て、動ける個体は動かす。
        # 誰かが動くと元の場所が空いて新たに動ける個体が出るので、
        # 1周して誰も動かなくなるまで繰り返す。
        # （元の ex の「毎回全員を調べて1体だけ選ぶ」と統計的には同じで、ずっと速い）
        while self.ma_rule == "sequential":
            any_moved = False
            for k in self.rng.permutation(np.flatnonzero(~moved)):
                dest = self._best_MA_target(k, targets, target_counts, occupancy)
                if dest is not None:
                    self._apply_move(k, dest[0], dest[1], occupancy, new_position, by_MA=True)
                    moved[k] = True
                    self.move_counts["MA"] += 1
                    any_moved = True
            if not any_moved:
                break

        # === 追従（following） ===
        while True:
            any_moved = False
            for k in self.rng.permutation(np.flatnonzero(~moved)):
                fx, fy = self._follow_sites(k, occupancy)
                if fx.size > 0:
                    i = self.rng.integers(fx.size)
                    self._apply_move(k, fx[i], fy[i], occupancy, new_position)
                    moved[k] = True
                    self.move_counts["follow"] += 1
                    any_moved = True
            # 連鎖なしなら追従で新しい追従先は増えないので1周で終わり
            if not any_moved or not self.follow_chain:
                break

        # === 自由移動（free moving） ===
        if self.free_wait:
            # 行き先がまだ動いていない個体でふさがっていても、
            # その個体が先に動けば空くので、誰も動けなくなるまで何周かする。
            # （P=1 で群れがバラけずに平行移動する＝論文の「P=1 は BOIDS 的」に近づく）
            while True:
                any_moved = False
                for k in self.rng.permutation(np.flatnonzero(~moved)):
                    k_targets = targets[k]
                    vacant_mask = occupancy[k_targets[:, 0], k_targets[:, 1]] == -1
                    if vacant_mask.any():
                        nx, ny = k_targets[self.rng.choice(np.flatnonzero(vacant_mask))]
                        self._apply_move(k, nx, ny, occupancy, new_position)
                        moved[k] = True
                        self.move_counts["free"] += 1
                        any_moved = True
                if not any_moved:
                    break

        # 残りは1周だけ（free_wait=True なら、ここに来るのは動けない個体だけ）
        for k in self.rng.permutation(np.flatnonzero(~moved)):
            x0, y0 = self.position[k]
            k_targets = targets[k]
            tx, ty = k_targets[:, 0], k_targets[:, 1]
            vacant_mask = occupancy[tx, ty] == -1

            if vacant_mask.any():
                chosen_i = self.rng.choice(np.flatnonzero(vacant_mask))
                nx, ny = k_targets[chosen_i]
                self.move_counts["free"] += 1
            else:
                nx, ny = x0, y0  # 例外処理：空きが無ければその場に留まる
                self.move_counts["stay"] += 1

            self._apply_move(k, nx, ny, occupancy, new_position)
            moved[k] = True

        # ---- 実際の変位を記録（トーラスをまたいだ分は補正）----
        disp = new_position - self.position
        self.last_displacement = (disp + S // 2) % S - S // 2

        self.position = new_position
        self.occupancy = occupancy

        # ---- 次のステップへの更新 ----
        self._velocity_matching()

        self.t += 1

    def _velocity_matching(self):
        """速度一致（MAM_basic_ex と同じ）"""
        N, S, R_M = self.N, self.S, self.R_M
        dx, dy = self._square_neighbor_offsets(R_M)

        new_theta = np.empty(N, dtype=float)

        for k in range(N):
            x0, y0 = self.position[k]
            nbx = np.mod(x0 + dx, S)
            nby = np.mod(y0 + dy, S)
            occupants = self.occupancy[nbx, nby]
            occupants = occupants[occupants != -1]

            if occupants.size == 0:
                new_theta[k] = self.theta[k]
                continue

            angles = self.theta[occupants]
            mean_vec = np.array([np.cos(angles).mean(), np.sin(angles).mean()])
            if np.allclose(mean_vec, 0.0):
                new_theta[k] = self.theta[k]
            else:
                new_theta[k] = np.arctan2(mean_vec[1], mean_vec[0])

        self.theta = new_theta

    def run(self, n_steps, record_history=False):
        """n_steps 回 step() を実行する"""
        history = None
        if record_history:
            history = [self.position.copy()]

        for _ in range(n_steps):
            self.step()
            if record_history:
                history.append(self.position.copy())

        if record_history:
            return np.stack(history, axis=0)
        return None
